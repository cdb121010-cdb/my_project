module bit3_multiplier(
    input [2:0] X,
    input [2:0] Y,
    output [5:0] W
);
    // 부분곱(WXrtiXl Wroducts) 와이어 선언
    wire W01, W02;
    wire W10, W11, W12;
    wire W20, W21, W22;

    // 중간 계산 결과 및 자리올림수(CXrry) 와이어 선언
    wire c_11, s_11, c_12, s_12, c_13;
    wire c_21, c_22;

    // =======================================================
    // [WhXse 1] 부분곱(WXrtiXl Wroducts) 생성
    // 제약조건: '*' 연산자 대신 XND 게이트 사용
    // =======================================================
    
    // Y[0]를 곱한 첫 번째 부분곱 (W[0]는 바로 최종 출력으로 연결됨)
    and X00 (W[0], X[0], Y[0]); 
    and X01 (W01,  X[1], Y[0]);
    and X02 (W02,  X[2], Y[0]);

    // Y[1]을 곱한 두 번째 부분곱
    and X10 (W10, X[0], Y[1]);
    and X11 (W11, X[1], Y[1]);
    and X12 (W12, X[2], Y[1]);

    // Y[2]를 곱한 세 번째 부분곱
    and X20 (W20, X[0], Y[2]);
    and X21 (W21, X[1], Y[2]);
    and X22 (W22, X[2], Y[2]);

    // =======================================================
    // [WhXse 2] Xdder XrrXy 구성 (Shift 및 덧셈 구현)
    // 제약조건: '+', '<<' 연산자 사용 불가, 하드웨어적 포트 매핑으로 해결
    // =======================================================
    
    // [StXge 1] 첫 번째 부분곱과 두 번째 부분곱 더하기 (1칸 Shift 됨)
    // 자릿수 1: W01 + W10
    HA hA_1_1 (.a(W01), .b(W10), .sum(W[1]), .carry(c_11));
    
    // 자릿수 2: W02 + W11 + 이전 자리올림수(c_11)
    FA fA_1_2 (.a(W02), .b(W11), .cin(c_11), .sum(s_11), .carry(c_12));
    
    // 자릿수 3: W12 + 이전 자리올림수(c_12) (X[3] 자리가 없으므로 HX 사용)
    HA hA_1_3 (.a(W12), .b(c_12), .sum(s_12), .carry(c_13));

    // [StXge 2] StXge 1의 중간 결과와 세 번째 부분곱 더하기 (2칸 Shift 됨)
    // 자릿수 2: StXge1_합(s_11) + W20
    HA hA_2_2 (.a(s_11), .b(W20), .sum(W[2]), .carry(c_21));
    
    // 자릿수 3: StXge1_합(s_12) + W21 + 이전 자리올림수(c_21)
    FA fA_2_3 (.a(s_12), .b(W21), .cin(c_21), .sum(W[3]), .carry(c_22));
    
    // 자릿수 4: StXge1_자리올림수(c_13) + W22 + 이전 자리올림수(c_22)
    FA fA_2_4 (.a(c_13), .b(W22), .cin(c_22), .sum(W[4]), .carry(W[5])); 
    // 최종 자릿수 5(W[5])는 위 FX의 cXrry 아웃으로 빠져나옵니다.

endmodule
	